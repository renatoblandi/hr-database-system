DROP DATABASE IF EXISTS capstone;

CREATE DATABASE IF NOT EXISTS capstone;

USE capstone;

CREATE TABLE IF NOT EXISTS departments (
    department_id CHAR(4) PRIMARY KEY,
    `name` VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS divisions (
    division_id INT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
    `name` VARCHAR(50) NOT NULL,
    department_id CHAR(4) NOT NULL,

    FOREIGN KEY (department_id) REFERENCES departments(department_id)
);

CREATE TABLE IF NOT EXISTS employees (
    employee_id INT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    date_hired DATE NOT NULL,
    phone_number VARCHAR(14) NOT NULL,
    email VARCHAR(100) UNIQUE NOT NULL,
    date_of_birth DATE NOT NULL,
    social_insurance_number CHAR(11) UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS unions (
    union_id INT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
    `name` VARCHAR(100) NOT NULL
);

CREATE TABLE positions (
    position_id INT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
    title VARCHAR(50) UNIQUE NOT NULL,
    `description` VARCHAR(255) NOT NULL,
    quantity INT NOT NULL,
    department_id CHAR(4) NOT NULL,
    division_id INT UNSIGNED,
    union_id INT UNSIGNED,

    FOREIGN KEY (department_id) REFERENCES departments(department_id),
    FOREIGN KEY (division_id) REFERENCES divisions(division_id),
    FOREIGN KEY (union_id) REFERENCES unions(union_id)
);

CREATE TABLE IF NOT EXISTS reports_to (
    subordinate_position_id INT UNSIGNED NOT NULL,
    supervisor_position_id INT UNSIGNED NOT NULL,

    PRIMARY KEY (subordinate_position_id, supervisor_position_id),
    FOREIGN KEY (subordinate_position_id) REFERENCES positions(position_id),
    FOREIGN KEY (supervisor_position_id) REFERENCES positions(position_id)
);

CREATE TABLE IF NOT EXISTS pay_rules (
    pay_rule_id INT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
    position_id INT UNSIGNED NOT NULL,
    min_years SMALLINT UNSIGNED NOT NULL,
    hourly_rate DECIMAL(5, 2),
    start_date DATE NOT NULL,
    end_date DATE,

    FOREIGN KEY (position_id) REFERENCES positions(position_id)
);

CREATE TABLE IF NOT EXISTS employment_history (
    employment_history_id INT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
    employee_id INT UNSIGNED NOT NULL,
    position_id INT UNSIGNED NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE,

    FOREIGN KEY (employee_id) REFERENCES employees(employee_id),
    FOREIGN KEY (position_id) REFERENCES positions(position_id)
);

